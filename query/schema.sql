-- ------------------------------------------------------------
-- <language>.source
-- ------------------------------------------------------------
-- Specific real-world place a word was actually encountered
-- (e.g. "Uniqlo", "Google Maps", "7-Eleven") — the encounter record. scene_id
-- is the kind of place it is (Uniqlo → clothing store).
CREATE TABLE japanese.source (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    url text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    scene_id bigint REFERENCES public.scene(id)
);

CREATE INDEX idx_source_scene_id ON japanese.source (scene_id);

-- ------------------------------------------------------------
-- <language>.word (formerly public.kotoba)
-- ------------------------------------------------------------
CREATE TABLE japanese.word (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word character varying NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc'::text),
    reading text,
    part_of_speech text DEFAULT 'noun'::text,
    updated_at timestamp with time zone DEFAULT now(),
    meanings text[] NOT NULL,
    sub_part_of_speech text,
    source_id bigint REFERENCES japanese.source(id),
    kana_type text NOT NULL CHECK (kana_type IN ('kanji', 'hiragana', 'katakana')),
    learned boolean NOT NULL DEFAULT false,
    meaning_id bigint REFERENCES public.meaning(id),
    level text,
    scene_id bigint REFERENCES public.scene(id)
);

CREATE INDEX idx_word_part_of_speech ON japanese.word (part_of_speech);
CREATE INDEX idx_word_sub_part_of_speech ON japanese.word (sub_part_of_speech);
