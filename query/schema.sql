-- ============================================================
-- language
-- ============================================================
-- Every language the app supports. The flags drive which columns and filters
-- the UI shows, so adding a language is a row here plus content rather than a
-- hunt through hardcoded conditionals. kotoba/sentences/grammar_point/
-- resource/resource_channel.language are foreign keys onto code.
CREATE TABLE public.language (
    code text PRIMARY KEY,
    name text NOT NULL,
    script text NOT NULL,
    direction text NOT NULL DEFAULT 'ltr' CHECK (direction IN ('ltr', 'rtl')),
    level_system text,
    has_reading boolean NOT NULL DEFAULT false,
    has_gender boolean NOT NULL DEFAULT false,
    has_characters boolean NOT NULL DEFAULT false,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

-- Seeded: ja (japanese/jlpt), de (latin/cefr), zh (han/hsk).

ALTER TABLE public.language ENABLE ROW LEVEL SECURITY;

