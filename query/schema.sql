-- ============================================================
-- Notes
-- ============================================================
-- Single-user app: RLS is enabled on every table with one open policy per
-- table ("allow all - anon") granting full SELECT/INSERT/UPDATE/DELETE to
-- the anon and authenticated roles. There is no user_id column anywhere and
-- no per-row ownership — access control is just "has the Supabase API key",
-- not per-user. If this ever becomes multi-user, these policies and the
-- schema (user_id columns) both need revisiting.
--
-- context.kind distinguishes "concrete" contexts (a real place you visited,
-- e.g. Restaurant, Station — originally curated as ~10-word situational
-- sets) from "abstract" contexts (a topic/semantic category, e.g. Color,
-- Time / Date — used for otherwise-unclassifiable systematic vocabulary).
--
-- source is a further refinement of context: context is the general
-- category ("Clothing Store"), source is the specific real-world instance
-- ("Uniqlo", uniqlo.com). kotoba.source_id is one-to-one per word (a word
-- has at most one recorded source), and source.context_id optionally rolls
-- a specific source up into its general category.
--
-- kotoba.kana_type classifies the word's writing system: 'kanji' if it
-- contains any kanji character (regardless of mixed-in okurigana), else
-- 'katakana' or 'hiragana' for kana-only words. Replaces the old has_kanji
-- boolean. kotoba.reading is NULL for non-kanji words (kana_type != 'kanji'),
-- since the reading would just duplicate word there. It is nullable only so
-- non-Japanese rows can omit it; the kotoba_kana_type_required_for_ja
-- constraint keeps it mandatory for every language='ja' row.
--
-- kotoba.language makes the table multi-language: one row is one language's
-- realization of a word, never a wide row holding several languages. This is
-- deliberate — learned, context_id, source_id, sentences.word_id and
-- word_kanji.word_id are all per-language facts (you can know テーブル and not
-- yet know "der Tisch"), so merging languages into one row would either
-- conflate independent state or duplicate every relational column per
-- language. Adding a third language is therefore rows, not columns.
--
-- concept is the thin link tying those per-language rows together: one shared
-- meaning, realized once per language. Backfilled from the existing Japanese
-- vocabulary by lower(trim(meanings[1])), which also merged genuine synonyms
-- onto one concept (持ち帰り / お持ち帰り / テイクアウト all → "takeout"), so a
-- concept may legitimately hold several words in the SAME language, not just
-- one per language. concept_id is nullable because not every word maps
-- cleanly across languages — culturally specific vocabulary (畳, お盆) simply
-- stays single-language rather than getting a forced translation.
--
-- The German vocabulary was seeded from german/vocab/batch-NN.csv via
-- german/generate_german_sql.py, one German word per concept. Those rows are
-- machine-generated reference data, unlike the Japanese rows, which were built
-- from words actually encountered — so a German row inherits context_id and
-- meanings from its Japanese sibling (there was no real encounter to record)
-- and always has source_id NULL and learned false. 82 concepts are
-- deliberately Japanese-only: culturally specific vocabulary (畳, 弁当, 神社),
-- proper names (東京, 九州), counters and function words (一つ, 以上), and
-- polite/humble variants German has no register for (お父さん vs 父). Each
-- carries a note in the CSV explaining why.
--
-- category is the syllabus taxonomy and lives on concept. It supersedes what
-- kotoba.context_id was being used for, but context is deliberately left in
-- place for now rather than dropped — sentences, resource, source and captures
-- still reference it. Retiring it is a later step, once the app reads category.
--
-- concept.slug/tier/category_id came from syllabus/, a curated list of 1733
-- concepts. 1148 existing concepts were rewritten in place and 79 more folded
-- into them (Japanese register variants such as 父親/父 collapsing to one
-- "father"), so no word was orphaned. 260 concepts predate the syllabus and
-- keep slug NULL — Japan-specific vocabulary and abstractions too narrow for a
-- core list. The syllabus CSVs remain the source of truth; syllabus/validate.py
-- checks them and syllabus/upload_syllabus.py stages them for a migration.
--
-- kotoba.level replaces the per-language jlpt/cefr pair: one column whose scale
-- is implied by language.level_system (jlpt / cefr / hsk). jlpt and cefr are
-- still present because the app reads them; they go once it reads level.
--
-- sentences, grammar_point, resource and resource_channel each carry their own
-- language column so the app's global language toggle can scope them at the
-- query level. All existing rows defaulted to 'ja'. source deliberately has NO
-- language column: a shop or website is not inherently tied to one language and
-- could hold words in both, so the Source view derives its list from the
-- languages of the words pointing at each source instead.
--
-- concept is the one table the toggle never filters — it exists to compare
-- languages side by side, so scoping it to the active language would defeat it.
--
-- kotoba.gender/plural/cefr are German-only, guarded by the
-- kotoba_german_fields_only_for_de constraint so Japanese rows stay clean.
-- jlpt and cefr are deliberately separate columns rather than one generic
-- "level": they are different scales, and kotoba.jlpt is referenced in ~50
-- places across the app that all mean the Japanese scale specifically.
--
-- sentences.context_id is independent of kotoba.context_id: a single word
-- can have multiple example sentences that each show it used in a different
-- real-world situation (e.g. 予約 has one sentence set in a Restaurant and
-- another set in Travel), so context is assigned per-sentence, not inherited
-- from the word. Nullable, same as kotoba.context_id.
--
-- sentence_kotoba is a further refinement of sentences.word_id: word_id is
-- the single word a sentence was originally written to demonstrate, but a
-- sentence often incidentally uses several other vocabulary words too (e.g.
-- "会社の利益が増加した。" uses 会社, 利益, and 増加). sentence_kotoba records
-- every kotoba word genuinely present in a sentence (including its own
-- word_id), letting the UI show a sentence's full vocabulary breakdown by
-- part of speech instead of just its one primary word.
--
-- kanji.cluster is a free-text thematic grouping independent of grade/JLPT,
-- e.g. 一/二/三 belong to cluster 'number'. Nullable, plain text (no fixed
-- enum), same convention as kotoba.jlpt/grade.
--
-- resource_channel/resource is a reference library of external learning
-- content (YouTube/TikTok videos), imported from resources/youtube/ via
-- resources/scripts/export_resources.py + generate_seed_sql.py. It mirrors
-- the source/kotoba shape: resource_channel is the general source (a
-- channel), resource is the individual item (a video), and resource.
-- context_id optionally reuses the same context table as kotoba/sentences
-- for situational tagging. Unlike kotoba/sentences, these tables aren't
-- vocabulary data — resource.category is a content-type label (listening-
-- practice, shadowing, vocabulary, conversation, tips), not a grammar/word
-- classification. Extracting actual vocabulary/sentences out of these
-- videos into kotoba/sentences is a separate, not-yet-built pipeline.
