-- ============================================================
-- source
-- ============================================================
-- Specific real-world place a kotoba word was actually encountered
-- (e.g. "Uniqlo", "Google Maps", "7-Eleven") — more granular than the
-- general context category (e.g. "Clothing Store", "Konbini").
