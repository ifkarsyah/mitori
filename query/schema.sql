-- ============================================================
-- category
-- ============================================================
-- Hierarchical vocabulary syllabus, two levels deep. Sits on concept rather
-- than kotoba because "apple is a fruit" holds in every language, whereas
-- "I saw this word at a Family Mart" is one encounter in one language — that
-- stays on kotoba.source_id. kind separates core categories (the objects and
-- ideas: chair, apple) from situational ones (the transaction vocabulary you
-- need in a place: bill, fitting room, residence card).
CREATE TABLE public.category (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    name text NOT NULL,
    parent_id bigint REFERENCES public.category(id),
    kind text NOT NULL CHECK (kind IN ('core', 'situational')),
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_category_parent_id ON public.category (parent_id);
CREATE INDEX idx_category_kind ON public.category (kind);

ALTER TABLE public.category ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow all - anon" ON public.category FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- ============================================================
-- concept
-- ============================================================
-- Language-agnostic meaning shared across languages ("chair", "teacher").
-- A kotoba row is one language's realization of a concept.
CREATE TABLE public.concept (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gloss text NOT NULL UNIQUE,
    part_of_speech text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    slug text UNIQUE,
    category_id bigint REFERENCES public.category(id),
    tier integer CHECK (tier BETWEEN 1 AND 3)
);

COMMENT ON TABLE public.concept IS 'Language-agnostic meaning shared across languages (e.g. "chair", "teacher"). A kotoba row is one language''s realization of a concept; concept_id is nullable because not every word maps cleanly across languages.';
COMMENT ON COLUMN public.concept.slug IS 'Stable syllabus identifier. NULL means the concept predates the syllabus and was not folded into it.';
COMMENT ON COLUMN public.concept.tier IS 'Study priority 1-3, so 1700+ concepts can be worked in a sensible order.';

CREATE INDEX idx_concept_category_id ON public.concept (category_id);
CREATE INDEX idx_concept_tier ON public.concept (tier);

ALTER TABLE public.concept ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow all - anon" ON public.concept FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- ============================================================
-- kotoba (core vocabulary; formerly "words")
-- ============================================================
CREATE TABLE public.kotoba (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word character varying NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc'::text),
    context_id bigint REFERENCES public.context(id),
    reading text,
    part_of_speech text DEFAULT 'noun'::text,
    updated_at timestamp with time zone DEFAULT now(),
    meanings text[] NOT NULL,
    sub_part_of_speech text,
    jlpt text,
    source_id bigint REFERENCES public.source(id),
    kana_type text CHECK (kana_type IN ('kanji', 'hiragana', 'katakana')),
    learned boolean NOT NULL DEFAULT false,
    language text NOT NULL DEFAULT 'ja' REFERENCES public.language(code),
    concept_id bigint REFERENCES public.concept(id),
    gender text CHECK (gender IN ('der', 'die', 'das')),
    plural text,
    cefr text,
    level text,
    CONSTRAINT kotoba_kana_type_required_for_ja
        CHECK (language <> 'ja' OR kana_type IS NOT NULL),
    CONSTRAINT kotoba_gendered_fields_only_for_de
        CHECK (language = 'de' OR (gender IS NULL AND plural IS NULL))
);

COMMENT ON TABLE public.kotoba IS 'Core vocabulary table. One row per word per language.';

CREATE INDEX idx_kotoba_context_id ON public.kotoba (context_id);
CREATE INDEX idx_kotoba_part_of_speech ON public.kotoba (part_of_speech);
CREATE INDEX idx_kotoba_sub_part_of_speech ON public.kotoba (sub_part_of_speech);
CREATE INDEX idx_kotoba_kana_type ON public.kotoba (kana_type);
CREATE INDEX idx_kotoba_jlpt ON public.kotoba (jlpt);
CREATE INDEX idx_kotoba_source_id ON public.kotoba (source_id);
CREATE INDEX idx_kotoba_language ON public.kotoba (language);
CREATE INDEX idx_kotoba_concept_id ON public.kotoba (concept_id);
