-- mitori database schema
-- Supabase project: mitori (gvwewkzwwzuvacbldxae)
-- Exported from live database. Not a migration history — a snapshot of current structure.
--
-- Layout: public holds only what is true in every language (language,
-- category, meaning, scene, scene_meaning, captures). Each language has its own
-- schema — japanese, german, chinese — with the same core tables (source, word, sentence,
-- sentence_word, grammar_point, resource_channel, resource) plus whatever only
-- that language needs (japanese.kanji/word_kanji, chinese.simplification).
-- Every language schema must also be listed under Supabase Dashboard → API →
-- Exposed schemas, or PostgREST will not serve it.

-- ============================================================
-- public.language
-- ============================================================
-- Every language the app supports. The flags drive which columns and filters
-- the UI shows, so adding a language is a row here, a schema, and content
-- rather than a hunt through hardcoded conditionals. schema_name is the
-- Postgres schema holding that language's tables.
CREATE TABLE public.language (
    code text PRIMARY KEY,
    name text NOT NULL,
    script text NOT NULL,
    direction text NOT NULL DEFAULT 'ltr' CHECK (direction IN ('ltr', 'rtl')),
    level_system text,
    has_reading boolean NOT NULL DEFAULT false,
    has_gender boolean NOT NULL DEFAULT false,
    has_characters boolean NOT NULL DEFAULT false,
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    schema_name text NOT NULL UNIQUE
);

-- Seeded: ja (japanese/jlpt), de (german/cefr), zh (chinese/hsk).

ALTER TABLE public.language ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow all - anon" ON public.language FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- ============================================================
-- public.category
-- ============================================================
-- Hierarchical vocabulary syllabus, two levels deep: what a word is about
-- (fruit, drinks, body parts, banking), never where you use it — that is a
-- scene. Sits on meaning rather than word because "apple is a fruit" holds in
-- every language, whereas "I saw this word at a Family Mart" is one encounter
-- in one language — that stays on <language>.word.source_id.
CREATE TABLE public.category (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    name text NOT NULL,
    parent_id bigint REFERENCES public.category(id),
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_category_parent_id ON public.category (parent_id);

ALTER TABLE public.category ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow all - anon" ON public.category FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- ============================================================
-- public.meaning
-- ============================================================
-- Language-agnostic meaning shared across languages ("chair", "teacher").
-- A <language>.word row is one language's realization of a meaning.
CREATE TABLE public.meaning (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gloss text NOT NULL UNIQUE,
    part_of_speech text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    slug text UNIQUE,
    category_id bigint REFERENCES public.category(id),
    tier integer CHECK (tier BETWEEN 1 AND 3)
);

COMMENT ON TABLE public.meaning IS 'Language-agnostic meaning shared across languages (e.g. "chair", "bento box"). A <language>.word row is one language''s word for a meaning; meaning_id is nullable because not every word maps cleanly across languages.';
COMMENT ON COLUMN public.meaning.slug IS 'Stable syllabus identifier. NULL means the meaning predates the syllabus and was not folded into it.';
COMMENT ON COLUMN public.meaning.tier IS 'Study priority 1-3, so 1700+ meanings can be worked in a sensible order.';

CREATE INDEX idx_meaning_category_id ON public.meaning (category_id);
CREATE INDEX idx_meaning_tier ON public.meaning (tier);

ALTER TABLE public.meaning ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow all - anon" ON public.meaning FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- ============================================================
-- public.scene
-- ============================================================
-- A real-world place: restaurant, hospital, konbini, home, or online (websites
-- and apps). General scenes have language NULL and are shared by every
-- language; a language-specific one (konbini checkout, hanabi) carries its
-- language code and usually narrows a general scene through parent_id.
CREATE TABLE public.scene (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    name text NOT NULL,
    description text,
    parent_id bigint REFERENCES public.scene(id),
    language text REFERENCES public.language(code),
    sort_order integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX idx_scene_parent_id ON public.scene (parent_id);
CREATE INDEX idx_scene_language ON public.scene (language);

ALTER TABLE public.scene ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow all - anon" ON public.scene FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- ============================================================
-- public.scene_meaning
-- ============================================================
-- Which meanings you need in a scene. Many-to-many: "receipt" belongs to
-- several places, while its category (money & shopping) is single.
CREATE TABLE public.scene_meaning (
    scene_id bigint NOT NULL REFERENCES public.scene(id),
    meaning_id bigint NOT NULL REFERENCES public.meaning(id),
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (scene_id, meaning_id)
);

CREATE INDEX idx_scene_meaning_meaning_id ON public.scene_meaning (meaning_id);

ALTER TABLE public.scene_meaning ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow all - anon" ON public.scene_meaning FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

