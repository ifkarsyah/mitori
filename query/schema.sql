-- ============================================================
-- Notes
-- ============================================================
-- Single-user app: RLS is enabled on every table with one open policy per
-- table ("allow all - anon") granting full SELECT/INSERT/UPDATE/DELETE to
-- the anon and authenticated roles. There is no user_id column anywhere and
-- no per-row ownership — access control is just "has the Supabase API key",
-- not per-user. If this ever becomes multi-user, these policies and the
-- schema (user_id columns) both need revisiting.
--
-- Schema per language (since 2026-10-27; before that everything lived in
-- public with a language column on kotoba/sentences/grammar_point/resource/
-- resource_channel). The schema now says which language a row is in, so those
-- language columns are gone, and each word table holds only its own fields:
-- reading/kana_type/sub_part_of_speech for Japanese, gender/plural for German,
-- reading (pinyin) for Chinese. The split kept every id, so ids are unique
-- across languages for rows that existed then — but each schema has its own
-- sequence from here on, so a word id is only unique within its language.
-- Adding a language: a language row with schema_name, a schema with the core
-- tables, grants and policies, and an entry under Exposed schemas.
--
-- Words are one row per language, never a wide row holding several languages.
-- learned, source_id, sentence.word_id and word_kanji.word_id are all
-- per-language facts (you can know テーブル and not yet know "der Tisch"), so
-- merging languages into one row would either conflate independent state or
-- duplicate every relational column per language.
--
-- meaning was called concept until 2026-10-27; renamed because "concept" was
-- too abstract. Its gloss is only an English label for the idea, not an
-- English word — that is why it isn't called english_word. The syllabus CSVs
-- under syllabus/concepts/ keep the old name in their files and columns.
--
-- meaning is the thin link tying those per-language rows together: one shared
-- meaning, realized once per language. Backfilled from the existing Japanese
-- vocabulary by lower(trim(meanings[1])), which also merged genuine synonyms
-- onto one meaning (持ち帰り / お持ち帰り / テイクアウト all → "takeout"), so a
-- meaning may legitimately hold several words in the SAME language, not just
-- one per language. meaning_id is nullable because not every word maps
-- cleanly across languages — culturally specific vocabulary (畳, お盆) simply
-- stays single-language rather than getting a forced translation.
--
-- The German vocabulary was seeded from german/vocab/batch-NN.csv, one German
-- word per meaning. Those rows are machine-generated reference data, unlike
-- the Japanese rows, which were built from words actually encountered — so a
-- German row inherits its meanings from its Japanese sibling (there was no
-- real encounter to record) and always has source_id NULL and learned false.
-- 82 meanings are deliberately Japanese-only: culturally specific vocabulary
-- (畳, 弁当, 神社), proper names (東京, 九州), counters and function words
-- (一つ, 以上), and polite/humble variants German has no register for (お父さん
-- vs 父). Each carries a note in the CSV explaining why. scripts/upload_vocab.py
-- loads vocab/<code>/*.csv into that language's word table.
--
-- category replaced the old public.context table (unrelated to today's scene). context was conflating two things:
-- the syllabus grouping of a meaning ("bill is restaurant vocabulary", true in
-- every language) and the record of a personal encounter ("I saw 割引 at a
-- Family Mart"). The first is category on meaning; the second is
-- word.source_id. A word's grouping comes from the meaning it realizes.
--
-- category and scene were split later: category had also held 17 "situational"
-- place-categories (restaurant, hospital, ...). Those became public.scene rows
-- with the same slugs; their meanings were re-filed into vocabulary categories
-- (some new: dishes, eating-out, housing, medical, personal-care, lodging,
-- banking, online-shopping, post) and kept their place as scene_meaning rows.
-- The per-language scene tables merged into public.scene.
--
-- meaning.slug/tier/category_id came from syllabus/, a curated list of 1733
-- meanings. 1148 existing meanings were rewritten in place and 79 more folded
-- into them (Japanese register variants such as 父親/父 collapsing to one
-- "father"), so no word was orphaned. 260 meanings predate the syllabus and
-- keep slug NULL — Japan-specific vocabulary and abstractions too narrow for a
-- core list. The syllabus CSVs remain the source of truth; syllabus/validate.py
-- checks them and syllabus/upload_syllabus.py stages them for a migration.
--
-- word.level is the single proficiency column; its scale is implied by
-- language.level_system (jlpt / cefr / hsk). kanji.jlpt is separate — that
-- table is Japanese by nature.
--
-- meaning is never filtered by language — it exists to compare languages side
-- by side, so the app reads every language's word table for meaning views.
--
-- sentence.scene_id is assigned per sentence rather than inherited from the
-- word: one word can have example sentences set in different places (予約 at
-- a Restaurant and again at a Hotel). sentence.category_id is the topic, for
-- sentences not set anywhere in particular.
--
-- A phrase is a sentence with a scene_id and no word_id: a set expression
-- of a situation (お弁当温めますか？ at konbini checkout) rather than an
-- example sentence for one word. sentence_word still links the words it uses.
-- The Sentences dashboard shows only rows with a word_id; phrases appear on
-- their scene's page. word.scene_id is a single FK on purpose — a word's
-- broad grouping already comes from meaning → category.
--
-- sentence_word is a further refinement of sentence.word_id: word_id is the
-- single word a sentence was originally written to demonstrate, but a
-- sentence often incidentally uses several other vocabulary words too (e.g.
-- "会社の利益が増加した。" uses 会社, 利益, and 増加). sentence_word records
-- every word genuinely present in a sentence (including its own word_id),
-- letting the UI show a sentence's full vocabulary breakdown by part of speech
-- instead of just its one primary word.
--
-- kanji.cluster is a free-text thematic grouping independent of grade/JLPT,
-- e.g. 一/二/三 belong to cluster 'number'. Nullable, plain text (no fixed
-- enum), same convention as kanji.jlpt/grade.
--
-- resource_channel/resource is a reference library of external learning
-- content (YouTube/TikTok videos), imported from resources/youtube/ via
-- resources/scripts/export_resources.py + generate_seed_sql.py. It mirrors
-- the source/word shape: resource_channel is the general source (a channel),
-- resource is the individual item (a video), and resource.category_id /
-- scene_id optionally file it under the same category tree and scenes as
-- meanings and sentences. resource.category is a content-type label
-- (listening-practice, shadowing, vocabulary, conversation, tips), not a
-- grammar/word classification.
