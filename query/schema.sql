CREATE INDEX idx_word_source_id ON japanese.word (source_id);
CREATE INDEX idx_word_meaning_id ON japanese.word (meaning_id);
CREATE INDEX idx_word_level ON japanese.word (level);
CREATE INDEX idx_word_scene_id ON japanese.word (scene_id);

